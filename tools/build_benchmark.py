"""Reproduce synthetic inputs and pre-run labels, without importing the system.

Regular price expectations are policy-regression targets, not market truth.
Hard cases are loaded from owner-approved external source snapshots, not
generated by the regular rulebook. Labels were reviewed before evaluation.
"""

from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP
import json
from pathlib import Path
import random

from hard_case_design import hard_cases


ROOT = Path(__file__).resolve().parents[1]
SEED = 20261002
AUTHOR = "Codex development assistant"


def reference_regular_price(rooms, stay, market, level):
    """Independent implementation of the declared illustrative policy oracle.

    Deliberate shared rulebook: this checks consistency, NOT economic validity.
    No pricing/service module or classifier is imported.
    """
    if level == "uncertain":
        return None
    inventory = Decimal(".10") if rooms < 10 else (Decimal("-.05") if rooms >= 24 else Decimal(0))
    weekend = Decimal(".05") if stay.weekday() in (4, 5) else Decimal(0)
    event = {"high": Decimal(".15"), "medium": Decimal(".05"), "low": Decimal(0)}[level]
    anchor = (Decimal(150) + Decimal(market)) / 2
    return int((anchor * (1 + inventory + weekend + event)).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def regular_cases():
    rng = random.Random(SEED)
    levels = ["high"] * 50 + ["medium"] * 50 + ["low"] * 80 + ["uncertain"] * 20
    rng.shuffle(levels)
    ref = date(2026, 10, 2)
    texts = {
        "high": [
            "Synthetic scenario: an international concert in Singapore on {stay} brings many visitors needing overnight accommodation.",
            "Synthetic scenario: a Formula 1 race in Singapore spans {stay}; large numbers of overseas spectators require overnight stays.",
        ],
        "medium": [
            "Synthetic scenario: a regional festival in Singapore on {stay} attracts some out-of-town visitors staying overnight, but most visitors are local.",
            "Synthetic scenario: a trade fair in Singapore on {stay} includes regional exhibitors seeking overnight accommodation.",
        ],
        "low": [
            "Synthetic scenario: a community fair in Singapore on {stay} serves nearby residents with no overnight visitor demand.",
            "Synthetic scenario: no local events are reported for {stay}; the supplied information clearly describes an ordinary day.",
        ],
        "uncertain": [
            "Synthetic scenario: an unconfirmed rumour mentions a gathering around {stay}, with no dependable venue or visitor details.",
            "Synthetic scenario: somebody mentions a possible gathering near {stay}, but its date, location and scale are not known.",
        ],
    }
    cases, gold = [], []
    for index, level in enumerate(levels):
        stay = ref + timedelta(days=rng.randrange(90))
        inventory_band = index % 3
        rooms = rng.randint(1, 9) if inventory_band == 0 else (rng.randint(10, 23) if inventory_band == 1 else rng.randint(24, 40))
        market = rng.choice([120, 140, 150, 160, 180])
        identifier = f"R{index + 1:03}"
        inputs = {
            "as_of_date": ref.isoformat(), "target_date": stay.isoformat(),
            "remaining_rooms": rooms, "competitor_prices_sgd": [market - 5, market, market + 5],
            "weather": rng.choice(["clear", "cloudy", "rain"]),
            "event_description": rng.choice(texts[level]).format(stay=stay.isoformat()),
            "source_type": "synthetic", "source_note": "Generated synthetic benchmark; no live quotes or calendar lookup.",
        }
        price = reference_regular_price(rooms, stay, market, level)
        cases.append({"case_id": identifier, "group": "regular", "input": inputs})
        gold.append({
            "case_id": identifier, "group": "regular",
            "expected_event_impact": level, "expected_human_review": level == "uncertain",
            "expected_guardrail_codes": ["EVENT_UNCERTAIN"] if level == "uncertain" else [],
            "acceptable_price_min": None if price is None else price - 5,
            "acceptable_price_max": None if price is None else price + 5,
            "reference_policy_price": price,
            "label_rationale": "Assigned synthetic activity meaning and declared policy-regression price ±SGD 5. Not an optimal market price.",
            "author": AUTHOR, "independent": False,
            "label_status": "author_proposed_pre_run",
            "gold_basis": "synthetic_semantics_and_policy_regression",
        })
    return cases, gold


def jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(row, ensure_ascii=False, allow_nan=False, sort_keys=True) + "\n" for row in rows), encoding="utf-8")


def main():
    if (ROOT / "data/freeze.json").exists():
        raise SystemExit("Benchmark already frozen. Do not overwrite it; use a documented new benchmark version.")
    regular, regular_gold = regular_cases()
    hard, hard_gold = hard_cases()
    jsonl(ROOT / "data/regular.jsonl", regular)
    jsonl(ROOT / "data/hard.jsonl", hard)
    jsonl(ROOT / "gold/regular_gold.jsonl", regular_gold)
    jsonl(ROOT / "gold/hard_gold.jsonl", hard_gold)
    print(f"Built {len(regular)} regular + {len(hard)} curated hard cases, with labels BEFORE any evaluation.")


if __name__ == "__main__":
    main()
